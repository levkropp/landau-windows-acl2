    def odd_sum_code(self):
        with self.narrate("odd_sum_code") as n:
            self.heading("Give the sum its actual ACL2 definition")
            meaning=T("O(n): sum of the first n odd numbers",size=29,color=TRUTH).move_to([0,1.05,0])
            recurrence=M("O(n + 1) = O(n) + 2n + 1",size=37,color=PRED).move_to([0,-.15,0])
            self.play(FadeIn(meaning),FadeIn(recurrence),run_time=.8)
            n.at(2)
            popup=FunctionPopup("teaching-examples.lisp","video-odd-sum","Input discussed here: natural n")
            self.play(FadeIn(popup,scale=.96),run_time=.8)
            n.at(3)
            focus=popup.focus(0);self.play(Create(focus),run_time=.6)
            n.at(4)
            self.play(Transform(focus,popup.focus(1)),run_time=.6)
            n.at(5)
            self.play(Transform(focus,popup.focus(2)),run_time=.6)
            n.at(6)
            self.play(Transform(focus,popup.focus(3)),Transform(popup.footer,
                      T("1- subtracts one: n → n − 1",size=24,color=TRUTH).move_to(popup.footer)),run_time=.6)
            n.at(9)
            self.play(FadeOut(focus),run_time=.4)
            example=T("n = 4: previous sum at 3, new odd term 7",size=24,color=TRUTH).move_to([0,-2.35,0])
            self.play(Transform(popup.footer,example),run_time=.6)
            n.at(11)
            self.play(Indicate(popup.body,color=TRUTH),run_time=1)
            n.at(13)
            badge=popup.badge("(video-odd-sum n)",(0,.1,0))
            self.play(ReplacementTransform(popup,badge),FadeOut(recurrence),run_time=.9)
            numeric=self.code("(video-odd-sum 4) → 16",size=31,color=GOOD).move_to([0,-1.45,0])
            self.play(FadeIn(numeric),run_time=.6)
            n.at(14)
            self.play(Indicate(badge,color=PRED),run_time=.9)
        self.wipe()
