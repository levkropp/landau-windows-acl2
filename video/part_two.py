def fraction(top, bottom, size=34, color=INK):
    numerator = M(str(top), size=size, color=color)
    denominator = M(str(bottom), size=size, color=color)
    bar = Line(LEFT * max(numerator.width,denominator.width)*.6,
               RIGHT * max(numerator.width,denominator.width)*.6, color=color)
    numerator.next_to(bar,UP,buff=.11)
    denominator.next_to(bar,DOWN,buff=.11)
    return VGroup(numerator,bar,denominator)


def expression(*parts, size=37):
    return VGroup(*[M(p,size=size) if isinstance(p,str) else p for p in parts]).arrange(RIGHT,buff=.28)


class RationalRuler(VGroup):
    """Font labels only: never invoke a TeX-backed number-line label."""
    def __init__(self, low, high, ticks, y=0, width=10.4, **kwargs):
        super().__init__(**kwargs)
        self.low,self.high,self.y,self.length=low,high,y,width
        self.add(Line(self.point(low),self.point(high),color=FAINT,stroke_width=2))
        for value,label in ticks:
            point=self.point(value)
            self.add(Line(point+UP*.08,point+DOWN*.08,color=DIM,stroke_width=2),
                     M(label,size=23,color=DIM).move_to(point+DOWN*.32))

    def point(self, value):
        return np.array([-self.length/2+(value-self.low)/(self.high-self.low)*self.length,self.y,0])

    def band(self, low, high, color=PRED):
        return VGroup(Line(self.point(low),self.point(high),color=color,stroke_width=10),
                      Dot(self.point(low),radius=.065,color=color),
                      Dot(self.point(high),radius=.065,color=color))


